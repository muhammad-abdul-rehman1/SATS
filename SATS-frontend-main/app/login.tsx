import React, { useState } from 'react';
import {
  View,
  Text,
  StyleSheet,
  TextInput,
  TouchableOpacity,
  Alert,
  KeyboardAvoidingView,
  Platform,
  ScrollView,
} from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { useSafeRouter } from '../hooks/useSafeRouter';
import { useAuth } from '../contexts/AuthContext';
import { ensureApiReachable, getEffectiveApiBaseUrl } from '../services/api';

export default function LoginScreen() {
  const router = useSafeRouter();
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [loading, setLoading] = useState(false);
  const [phase, setPhase] = useState<'idle' | 'discovering' | 'signing-in'>('idle');
  const [showPassword, setShowPassword] = useState(false);
  const { login } = useAuth();

  const handleLogin = async () => {
    if (!email || !password) {
      Alert.alert('Error', 'Please fill in all fields');
      return;
    }

    try {
      setLoading(true);
      setPhase('discovering');
      await ensureApiReachable({ onProgress: (msg) => console.log('[Discovery]', msg) });
      setPhase('signing-in');
      await login(email, password);
      router.replace('/(tabs)/assets');
    } catch (error: any) {
      const isNetworkError =
        error.message?.includes('Network Error') ||
        error.message?.includes('network') ||
        error.code === 'ERR_NETWORK' ||
        !error.response;

      if (isNetworkError) {
        let attemptedUrl = '';
        try {
          attemptedUrl = await getEffectiveApiBaseUrl();
        } catch (e) {}

        Alert.alert(
          'Connection Error',
          `Could not find the backend server automatically.\n\nLast tried: ${attemptedUrl || 'unknown'}\n\nMake sure the PC is running the backend and both devices are on the same Wi-Fi. The app will keep auto-detecting on retry.`,
          [
            { text: 'Retry', onPress: () => handleLogin() },
            { text: 'Cancel', style: 'cancel' },
          ]
        );
      } else {
        Alert.alert('Login Failed', error.response?.data?.message || 'Invalid credentials');
      }
    } finally {
      setLoading(false);
      setPhase('idle');
    }
  };

  const handleRegister = () => {
    router.push('/register');
  };

  return (
    <KeyboardAvoidingView 
      style={styles.container} 
      behavior={Platform.OS === 'ios' ? 'padding' : 'height'}
    >
      <ScrollView contentContainerStyle={styles.scrollContainer}>
        <View style={styles.header}>
          <View style={styles.logo}>
            <Ionicons name="qr-code" size={60} color="#007AFF" />
          </View>
          <Text style={styles.title}>Smart Asset Tracker</Text>
          <Text style={styles.subtitle}>Sign in to your account</Text>
        </View>

        <View style={styles.form}>
          <View style={styles.inputContainer}>
            <Ionicons name="mail-outline" size={20} color="#666" style={styles.inputIcon} />
            <TextInput
              style={styles.input}
              placeholder="Email"
              value={email}
              onChangeText={setEmail}
              keyboardType="email-address"
              autoCapitalize="none"
              autoCorrect={false}
            />
          </View>

          <View style={styles.inputContainer}>
            <Ionicons name="lock-closed-outline" size={20} color="#666" style={styles.inputIcon} />
            <TextInput
              style={styles.input}
              placeholder="Password"
              value={password}
              onChangeText={setPassword}
              secureTextEntry={!showPassword}
              autoCapitalize="none"
              autoCorrect={false}
            />
            <TouchableOpacity
              style={styles.eyeIcon}
              onPress={() => setShowPassword(!showPassword)}
            >
              <Ionicons 
                name={showPassword ? "eye-outline" : "eye-off-outline"} 
                size={20} 
                color="#666" 
              />
            </TouchableOpacity>
          </View>

          <TouchableOpacity 
            style={styles.forgotPasswordButton} 
            onPress={() => router.push('/forgot-password')}
          >
            <Text style={styles.forgotPasswordText}>Forgot Password?</Text>
          </TouchableOpacity>

          <TouchableOpacity
            style={[styles.loginButton, loading && styles.loginButtonDisabled]}
            onPress={handleLogin}
            disabled={loading}
          >
            <Text style={styles.loginButtonText}>
              {phase === 'discovering'
                ? 'Finding Server...'
                : phase === 'signing-in'
                  ? 'Signing In...'
                  : 'Sign In'}
            </Text>
          </TouchableOpacity>

          <View style={styles.divider}>
            <View style={styles.dividerLine} />
            <Text style={styles.dividerText}>OR</Text>
            <View style={styles.dividerLine} />
          </View>

          <TouchableOpacity style={styles.registerButton} onPress={handleRegister}>
            <Text style={styles.registerButtonText}>Create New Account</Text>
          </TouchableOpacity>
        </View>

        <View style={styles.footer}>
          <Text style={styles.footerText}>
            Track your assets with QR codes and location services
          </Text>
        </View>
      </ScrollView>
    </KeyboardAvoidingView>
  );
}

